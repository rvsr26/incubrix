def test_upload_session_instruction_idempotency_and_render(client,sample_video,sample_words,tmp_path):
    data={'rights_confirmed':'true'}
    with sample_video.open('rb') as f:
        r=client.post('/api/v1/videos/upload',headers={'Idempotency-Key':'upload-1'},data=data,files={'file':('demo.mp4',f,'video/mp4')})
    assert r.status_code==200,r.text
    video=r.json()['video']
    source_path=Path(VIDEOS[video['video_id']]['path'])
    source_hash_before=sha256_file(source_path)
    # Same key and same request returns the first result.
    with sample_video.open('rb') as f:
        repeat=client.post('/api/v1/videos/upload',headers={'Idempotency-Key':'upload-1'},data=data,files={'file':('demo.mp4',f,'video/mp4')})
    assert repeat.status_code==200
    session=client.post('/api/v1/sessions',headers={'Idempotency-Key':'session-1'},json={'video_id':video['video_id'],'transcript':sample_words})
    assert session.status_code==200,session.text
    sid=session.json()['session_id']
    ins=client.post(f'/api/v1/sessions/{sid}/instructions',headers={'Idempotency-Key':'instruction-1'},json={'say':"Add a caption 'Welcome!' when I say welcome to the channel"})
    assert ins.json()['status']=='applied'
    timeline=client.get(f'/api/v1/sessions/{sid}/timeline').json()
    assert len(timeline['timeline']['captions'])==1
    job=client.post(f'/api/v1/sessions/{sid}/render',headers={'Idempotency-Key':'render-1'})
    assert job.status_code==202
    state=client.get(f"/api/v1/jobs/{job.json()['job_id']}").json()
    assert state['status']=='succeeded',state
    output=client.get(state['result']['local_video_url'])
    assert output.status_code==200
    out=tmp_path/'output.mp4';out.write_bytes(output.content)
    rendered=probe_video(out)
    assert abs(rendered['duration_s']-timeline['duration_s'])<=1/(video['fps_num']/video['fps_den'])+0.002
    assert sha256_file(source_path)==source_hash_before
    import json, subprocess
    probe=json.loads(subprocess.run(['ffprobe','-v','error','-show_streams','-of','json',str(out)],capture_output=True,text=True,check=True).stdout)
    durations={x['codec_type']:float(x['duration']) for x in probe['streams'] if x.get('duration')}
    assert abs(durations['video']-durations['audio'])<=1/(video['fps_num']/video['fps_den'])+0.002
    assert abs(durations['video']-timeline['duration_s'])<=1/(video['fps_num']/video['fps_den'])+0.002

