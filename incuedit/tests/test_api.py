def test_history_undo_redo_and_otio_endpoints(client, sample_video, sample_words):
    with sample_video.open('rb') as f:
        v = client.post('/api/v1/videos/upload', headers={'Idempotency-Key': 'hur-video'}, data={'rights_confirmed': 'true'}, files={'file': ('demo.mp4', f, 'video/mp4')}).json()['video']
    sid = client.post('/api/v1/sessions', headers={'Idempotency-Key': 'hur-session'}, json={'video_id': v['video_id'], 'transcript': sample_words}).json()['session_id']
    
    # 1. Apply edit
    c1 = client.post(f'/api/v1/sessions/{sid}/instructions', headers={'Idempotency-Key': 'hur-cut'}, json={'say': 'Cut the first 3 seconds'}).json()
    assert c1['status'] == 'applied'
    assert c1['duration_s'] == 13.0
    
    # 2. Get history
    hist = client.get(f'/api/v1/sessions/{sid}/history').json()
    assert len(hist['history']) == 1
    assert hist['history'][0]['label'] == 'Cut the first 3 seconds'
    
    # 3. Direct undo endpoint
    u = client.post(f'/api/v1/sessions/{sid}/undo', headers={'Idempotency-Key': 'hur-undo'}).json()
    assert u['status'] == 'applied'
    assert u['duration_s'] == 16.0
    
    # 4. Direct redo endpoint
    r = client.post(f'/api/v1/sessions/{sid}/redo', headers={'Idempotency-Key': 'hur-redo'}).json()
    assert r['status'] == 'applied'
    assert r['duration_s'] == 13.0
    
    # 5. OTIO export endpoint
    otio_res = client.get(f'/api/v1/sessions/{sid}/otio')
    assert otio_res.status_code == 200
    otio = otio_res.json()
    assert otio['OTIO_SCHEMA'] == 'Timeline.1'
    assert 'tracks' in otio
