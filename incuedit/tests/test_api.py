def test_upload_music_then_instruction(client,sample_video,sample_words,tmp_path):
    with sample_video.open('rb') as f:
        v=client.post('/api/v1/videos/upload',headers={'Idempotency-Key':'music-video'},data={'rights_confirmed':'true'},files={'file':('demo.mp4',f,'video/mp4')}).json()['video']
    sid=client.post('/api/v1/sessions',headers={'Idempotency-Key':'music-session'},json={'video_id':v['video_id'],'transcript':sample_words}).json()['session_id']
    # A valid short WAV fixture generated by FFmpeg.
    wav=tmp_path/'music.wav';subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-f','lavfi','-i','sine=frequency=220:duration=1',str(wav)],check=True)
    with wav.open('rb') as f:
        r=client.post(f'/api/v1/sessions/{sid}/music',headers={'Idempotency-Key':'music-up'},data={'rights_confirmed':'true'},files={'file':('music.wav',f,'audio/wav')})
    assert r.status_code==200,r.text
    add=client.post(f'/api/v1/sessions/{sid}/instructions',headers={'Idempotency-Key':'music-add'},json={'say':'Add background music'})
    assert add.json()['status']=='applied'


def test_background_music_render_stays_in_sync_after_cut(client,sample_video,sample_words,tmp_path):
    with sample_video.open('rb') as f:
        video=client.post('/api/v1/videos/upload',headers={'Idempotency-Key':'music-render-video'},data={'rights_confirmed':'true'},files={'file':('demo.mp4',f,'video/mp4')}).json()['video']
    sid=client.post('/api/v1/sessions',headers={'Idempotency-Key':'music-render-session'},json={'video_id':video['video_id'],'transcript':sample_words}).json()['session_id']
    wav=tmp_path/'music.wav'
    subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-f','lavfi','-i','sine=frequency=220:duration=20',str(wav)],check=True)
    with wav.open('rb') as f:
        music=client.post(f'/api/v1/sessions/{sid}/music',headers={'Idempotency-Key':'music-render-up'},data={'rights_confirmed':'true'},files={'file':('music.wav',f,'audio/wav')})
    assert music.status_code==200,music.text
    assert client.post(f'/api/v1/sessions/{sid}/instructions',headers={'Idempotency-Key':'music-render-add'},json={'say':'Add background music'}).json()['status']=='applied'
    assert client.post(f'/api/v1/sessions/{sid}/instructions',headers={'Idempotency-Key':'music-render-cut'},json={'say':'Cut the first 2 seconds'}).json()['status']=='applied'
    job=client.post(f'/api/v1/sessions/{sid}/render',headers={'Idempotency-Key':'music-render-start'}).json()
    state=client.get(f"/api/v1/jobs/{job['job_id']}").json()
    assert state['status']=='succeeded',state
    manifest=state['result']['manifest']
    assert manifest['sync_validation']['max_offset_frames']<=1
    assert manifest['sync_validation']['max_length_difference_frames']<=1


